//! Retention (Blaze, 27 Oct 2026: "the feeds room in oracle, make it delete its messages after 48 hours"). One owner-signed record,
//! `retention/1`, under the face `[Retention]` in #oracle, holds the table `{room: {ttl_hours}}`; the newest valid owner record is the
//! table, kept in its own row (`retention`) as `private-rooms/1` is. A record written into a room with a rule and no `expires:` tag of
//! its own gets `expires_ms = created + ttl`, so it leaves every read when its time is up (docs/ARCHIVE.md); records already in the
//! room are backfilled the moment the rule lands. `Store::sweep_expired` then removes the expired rows of those rooms from the store
//! and its indexes: feed records are regenerated by their feeds, so this is the one place Oracle deletes. Rooms without a rule keep
//! everything, as before.

use serde_json::Value;
use std::collections::BTreeMap;

pub const ROOM: &str = "oracle";
pub const FACE: &str = "[Retention]";
pub const SCHEMA: &str = "retention/1";
/// A year: longer than that is "keep", and the table should not say it.
pub const MAX_TTL_HOURS: u32 = 24 * 366;

#[derive(Clone, Debug, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
pub struct Rule {
    pub ttl_hours: u32,
}

/// `room → its rule`.
pub type Table = BTreeMap<String, Rule>;

use crate::naming::handle_ok as name_ok;

/// A record's table, or why it cannot be honoured. The CLI and the store use this one function.
pub fn parse(cargo: &str) -> Result<Table, String> {
    let v: Value = serde_json::from_str(cargo).map_err(|_| "the record is not JSON".to_string())?;
    if v["schema"] != SCHEMA {
        return Err(format!("the record's schema is not {SCHEMA}"));
    }
    let t: Table = serde_json::from_value(v["rooms"].clone()).map_err(|_| "the record has no rooms table".to_string())?;
    for (room, rule) in &t {
        if !name_ok(room) {
            return Err(format!("{room:?} is not a room name"));
        }
        // The room the table lives in, and the rooms that hold decisions and memory, are never swept by a rule in this table.
        if room == ROOM || room == "memory" || room == "board" {
            return Err(format!("#{room} cannot have a retention rule"));
        }
        if rule.ttl_hours == 0 || rule.ttl_hours > MAX_TTL_HOURS {
            return Err(format!("#{room}: ttl_hours must be 1 to {MAX_TTL_HOURS}"));
        }
    }
    Ok(t)
}

/// The record's cargo for a table.
pub fn cargo(t: &Table) -> String {
    serde_json::json!({"schema": SCHEMA, "rooms": t}).to_string()
}

/// When a record created at `created_ms` in `room` leaves the view under this table, or None when the room keeps everything.
pub fn expires_for(t: &Table, room: &str, created_ms: i64) -> Option<i64> {
    t.get(room).map(|r| created_ms + i64::from(r.ttl_hours) * 3_600_000)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_table_is_parsed_and_refused_for_the_right_reasons() {
        let t = parse(r#"{"schema":"retention/1","rooms":{"feeds":{"ttl_hours":48}}}"#).unwrap();
        assert_eq!(t["feeds"].ttl_hours, 48);
        assert_eq!(parse(&cargo(&t)).unwrap(), t, "what we write, we read");
        for bad in [
            r#"{"schema":"retention/0","rooms":{}}"#,
            r#"{"schema":"retention/1","rooms":{"Feeds":{"ttl_hours":48}}}"#,
            r#"{"schema":"retention/1","rooms":{"feeds":{"ttl_hours":0}}}"#,
            r#"{"schema":"retention/1","rooms":{"feeds":{"ttl_hours":9000}}}"#,
            r#"{"schema":"retention/1","rooms":{"oracle":{"ttl_hours":48}}}"#,
            r#"{"schema":"retention/1","rooms":{"memory":{"ttl_hours":48}}}"#,
            r#"{"schema":"retention/1","rooms":{"feeds":{"ttl":48}}}"#,
            "not json",
        ] {
            assert!(parse(bad).is_err(), "{bad} must be refused");
        }
    }

    #[test]
    fn a_room_with_a_rule_expires_and_a_room_without_keeps() {
        let t = parse(r#"{"schema":"retention/1","rooms":{"feeds":{"ttl_hours":48}}}"#).unwrap();
        assert_eq!(expires_for(&t, "feeds", 1_000), Some(1_000 + 48 * 3_600_000));
        assert_eq!(expires_for(&t, "oracle", 1_000), None);
    }
}
